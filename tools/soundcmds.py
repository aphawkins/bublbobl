"""Write notes/sound_commands.md from the sound-latch writes that trace.py logged.

Usage: python tools/soundcmds.py

Reads every build/traces/<scenario>/sound.csv. For each command byte the main CPU wrote
to FA00 it lists how often, in which runs, and from which instructions. What each
command plays is for the sound CPU disassembly (Phase 7) to say.
"""

import csv
import sys
from collections import defaultdict

import romset

ROOT = romset.ROOT
TRACE_DIR = ROOT / "build" / "traces"
OUT = ROOT / "notes" / "sound_commands.md"


def norm_pc(pc: str) -> str:
    bank, _, addr = pc.rpartition(":")
    addr = f"{int(addr, 16):04X}"
    return f"{bank}:{addr}" if bank else addr


def main() -> int:
    count = defaultdict(int)
    runs = defaultdict(set)
    senders = defaultdict(set)
    names = []
    for path in sorted(TRACE_DIR.glob("*/sound.csv")):
        names.append(path.parent.name)
        with path.open(newline="") as f:
            for row in csv.DictReader(f):
                cmd = int(row["cmd"], 16)
                count[cmd] += 1
                runs[cmd].add(path.parent.name)
                senders[cmd].add(norm_pc(row["pc"]))
    if not names:
        print("no sound logs: run tools/trace.py first", file=sys.stderr)
        return 1
    out = [
        "# Sound commands",
        "",
        "Generated by `tools/soundcmds.py` from MAME traces (`tools/trace.py`): every byte",
        "the main CPU wrote to the sound latch `FA00`. Do not edit.",
        "",
        "Runs: " + ", ".join(f"`{n}`" for n in names),
        "",
        "| Command | Writes | Runs | Written by |",
        "|---|---|---|---|",
    ]
    for cmd in sorted(count):
        out.append(f"| {cmd:02X} | {count[cmd]} | {', '.join(sorted(runs[cmd]))} | "
                   f"{', '.join(sorted(senders[cmd]))} |")
    out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(count)} commands from {len(names)} runs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
