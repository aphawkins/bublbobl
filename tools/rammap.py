"""Write notes/ram_map.md from the memory accesses that trace.py recorded.

Usage: python tools/rammap.py

Reads every build/traces/<scenario>/access.csv. For each RAM and I/O address it lists the
instructions that wrote and read it. Neighbouring addresses with the same writers and
readers are joined into one row. The work RAM at E000-F7FF is shared by the main and sub
CPUs, so its table has both. Names come from notes/symbols.toml; give an address a name
there, not in the generated file.
"""

import csv
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

import romset

ROOT = romset.ROOT
TRACE_DIR = ROOT / "build" / "traces"
OUT = ROOT / "notes" / "ram_map.md"
MAX_PCS = 8
BULK = 0x100  # an instruction that touches this many addresses in a region is "bulk"

# (title, block, [(cpu, lo, hi)]) -- one table each. Where block > 1, each aligned block
# of that many bytes is one unit: its accessors are the union over its bytes.
REGIONS = [
    ("Main CPU: object tile columns (C000-DCFF), by 0x80-byte gfx block", 0x80,
     [("main", 0xC000, 0xDCFF)]),
    ("Main CPU: object RAM (DD00-DFFF), by 0x20 bytes (8 objects)", 0x20,
     [("main", 0xDD00, 0xDFFF)]),
    ("Work RAM shared by the main and sub CPUs (E000-F7FF)", 1,
     [("main", 0xE000, 0xF7FF), ("sub", 0xE000, 0xF7FF)]),
    ("Main CPU: palette RAM (F800-F9FF), by 0x20-byte palette", 0x20,
     [("main", 0xF800, 0xF9FF)]),
    ("Main CPU: I/O (FA00-FBFF)", 1, [("main", 0xFA00, 0xFBFF)]),
    ("Main CPU: RAM shared with the MCU (FC00-FFFF)", 1, [("main", 0xFC00, 0xFFFF)]),
    ("Sound CPU: RAM (8000-8FFF)", 1, [("sound", 0x8000, 0x8FFF)]),
    ("Sound CPU: I/O (9000-BFFF)", 1, [("sound", 0x9000, 0xBFFF)]),
]

# symbol tables that name addresses for each CPU (region-sized entries are skipped)
NAME_TABLES = {"main": ["main.io", "main.mem", "shared.mcu"], "sub": ["sub.mem"],
               "sound": ["sound.io"]}


def load_names() -> dict[str, dict[int, str]]:
    data = tomllib.loads((ROOT / "notes" / "symbols.toml").read_text(encoding="utf-8"))
    names: dict[str, dict[int, str]] = {}
    for cpu, tables in NAME_TABLES.items():
        m = names.setdefault(cpu, {})
        for path in tables:
            t = data
            for key in path.split("."):
                t = t.get(key, {})
            for name, v in t.items():
                size = v.get("size", 1)
                if size >= 0x100:
                    continue
                for i in range(size):
                    m[v["addr"] + i] = name if i == 0 else f"{name}+{i}"
    return names


def load_access():
    """(cpu, addr) -> {"W": {pc: count}, "R": {pc: count}}"""
    acc = defaultdict(lambda: {"W": defaultdict(int), "R": defaultdict(int)})
    runs = []
    for path in sorted(TRACE_DIR.glob("*/access.csv")):
        runs.append(path.parent.name)
        with path.open(newline="") as f:
            for row in csv.DictReader(f):
                acc[(row["cpu"], int(row["addr"], 16))][row["kind"]][row["pc"]] += int(row["count"])
    return acc, runs


def pc_key(pc: str):
    bank, _, addr = pc.rpartition(":")
    return (bank, int(addr, 16))


def fmt(pcs) -> str:
    pcs = sorted(pcs, key=pc_key)
    if not pcs:
        return ""
    more = len(pcs) - MAX_PCS
    return ", ".join(pcs[:MAX_PCS]) + (f" +{more}" if more > 0 else "")


def main() -> int:
    acc, runs = load_access()
    if not runs:
        print("no access logs: run tools/trace.py first", file=sys.stderr)
        return 1
    names = load_names()
    out = [
        "# RAM and I/O map",
        "",
        "Generated by `tools/rammap.py` from MAME traces (`tools/trace.py`). Do not edit:",
        "name addresses in `notes/symbols.toml`, which this file reads. Each row is a run of",
        "addresses with the same writers and readers. Instruction addresses are main-CPU",
        "fixed ROM unless they say `bankN:`.",
        "",
        "Runs: " + ", ".join(f"`{r}`" for r in runs),
        "",
    ]
    for title, block, parts in REGIONS:
        rows = []
        lo, hi = parts[0][1], parts[0][2]
        # Bulk accessors (RAM tests, clears, block copies) touch BULK+ addresses here.
        # They are listed once above the table and left out of its rows.
        bulk = {}
        for cpu, _, _ in parts:
            for kind in "WR":
                reach = defaultdict(int)
                for a in range(lo, hi + 1):
                    for pc in acc[(cpu, a)][kind] if (cpu, a) in acc else ():
                        reach[pc] += 1
                bulk[(cpu, kind)] = {pc: n for pc, n in reach.items() if n >= BULK}

        def accessors(cpu, kind, a0, a1):
            got = set()
            for a in range(a0, a1):
                if (cpu, a) in acc:
                    got.update(acc[(cpu, a)][kind])
            return frozenset(got - bulk[(cpu, kind)].keys())

        for addr in range(lo, hi + 1, block):
            end = min(addr + block, hi + 1)
            sets = tuple((accessors(cpu, "W", addr, end), accessors(cpu, "R", addr, end))
                         for cpu, _, _ in parts)
            if not any(w or r for w, r in sets):
                continue
            name = "" if block > 1 else next(
                (names[cpu][addr] for cpu, _, _ in parts if addr in names.get(cpu, {})), "")
            # Join the previous row if contiguous, same accessors, and the same symbol
            # (or both unnamed). A symbol's first byte always starts a row.
            last = rows[-1] if rows else None
            if last and last["hi"] == addr - 1 and last["sets"] == sets \
                    and (not name or "+" in name) and name.split("+")[0] == last["name"]:
                last["hi"] = end - 1
            else:
                rows.append({"lo": addr, "hi": end - 1, "name": name, "sets": sets})
        if not rows:
            continue
        cpus = [cpu for cpu, _, _ in parts]
        head = "| Address | Size | Name |" + "".join(
            f" {cpu} writes | {cpu} reads |" for cpu in cpus)
        out += [f"## {title}", ""]
        for (cpu, kind), pcs in bulk.items():
            if pcs:
                what = "writes" if kind == "W" else "reads"
                out.append(f"Bulk {cpu} {what}: " + ", ".join(
                    f"{pc} ({n:#x})" for pc, n in sorted(pcs.items(), key=lambda i: pc_key(i[0]))))
                out.append("")
        out += [head, "|---" * (3 + 2 * len(cpus)) + "|"]
        for r in rows:
            size = r["hi"] - r["lo"] + 1
            addr = f"{r['lo']:04X}" if size == 1 else f"{r['lo']:04X}-{r['hi']:04X}"
            cells = "".join(f" {fmt(w)} | {fmt(rd)} |" for w, rd in r["sets"])
            out.append(f"| {addr} | {size:#x} | {r['name']} |{cells}")
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} from {len(runs)} runs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
