"""Seed and maintain the byte classification map of each CPU image.

Usage: python tools/classify.py [--roms DIR]

Each map is notes/classmap/<image>.toml, a list of [[range]] entries:
    start, end (inclusive, CPU addresses), kind (code/data/text/fill), source, note
Entries with source = "auto" are regenerated by this script on every run; every other
entry (e.g. source = "manual" or "trace") is kept as is. Bytes in no range are unknown.
"""

import argparse
import re
import sys
import tomllib
from pathlib import Path

import romset

ROOT = romset.ROOT
MAP_DIR = ROOT / "notes" / "classmap"
KINDS = {"code", "data", "text", "fill"}

MIN_FILL = 16  # shortest run of 0xFF / 0x00 recorded as fill
TEXT_CHARS = re.compile(rb"[A-Z0-9 .,!?:'\-~&()/\"]+")


def find_fill(data: bytes, base: int) -> list[dict]:
    out = []
    for m in re.finditer(rb"\xff{%d,}|\x00{%d,}" % (MIN_FILL, MIN_FILL), data):
        out.append(rng(base + m.start(), base + m.end() - 1, "fill",
                       f"{m.end() - m.start():#x} x {data[m.start()]:02X}"))
    return out


def find_text(data: bytes, base: int) -> list[dict]:
    """Length-prefixed ASCII: n, then n chars, at least 4 long, 60%+ of non-space chars letters.
    Candidates only: pointer tables can pass, so check before relying on one."""
    out = []
    i = 0
    while i < len(data) - 4:
        n = data[i]
        s = data[i + 1 : i + 1 + n]
        if 4 <= n <= 48 and len(s) == n and TEXT_CHARS.fullmatch(s) \
                and sum(65 <= c <= 90 for c in s) >= max(3, 0.6 * (n - s.count(b" "))):
            out.append(rng(base + i, base + i + n, "text", s.decode("ascii")))
            i += n + 1
        else:
            i += 1
    return out


def rng(start: int, end: int, kind: str, note: str, source: str = "auto") -> dict:
    return {"start": start, "end": end, "kind": kind, "source": source, "note": note}


def read_map(path: Path) -> list[dict]:
    if not path.exists():
        return []
    ranges = tomllib.loads(path.read_text(encoding="utf-8")).get("range", [])
    for r in ranges:
        if r["kind"] not in KINDS:
            raise ValueError(f"{path.name}: bad kind {r['kind']!r} at {r['start']:#06x}")
    return ranges


def write_map(path: Path, image: str, ranges: list[dict]) -> None:
    rom, off, length, base = romset.IMAGES[image]
    lines = [
        f"# Byte classification for {image} ({rom} +{off:#x}, {length:#x} bytes @ {base:04X}).",
        "# Generated in part by tools/classify.py: source=\"auto\" entries are rewritten.",
        "",
    ]
    for r in sorted(ranges, key=lambda r: (r["start"], r["end"])):
        note = r.get("note", "").replace("\\", "\\\\").replace('"', '\\"')
        lines += [
            "[[range]]",
            f"start = 0x{r['start']:04X}",
            f"end = 0x{r['end']:04X}",
            f'kind = "{r["kind"]}"',
            f'source = "{r["source"]}"',
            f'note = "{note}"',
            "",
        ]
    path.write_text("\n".join(lines), encoding="utf-8")


def overlaps(a: dict, b: dict) -> bool:
    return a["start"] <= b["end"] and b["start"] <= a["end"]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--roms", type=Path, help="ROM directory or zip")
    args = ap.parse_args()
    try:
        imgs = romset.images(romset.load(args.roms))
    except romset.RomError as e:
        print(e, file=sys.stderr)
        return 1
    MAP_DIR.mkdir(parents=True, exist_ok=True)
    for image, data in imgs.items():
        path = MAP_DIR / (Path(image).stem + ".toml")
        kept = [r for r in read_map(path) if r["source"] != "auto"]
        # Auto entries never override a kept (manual/trace) entry.
        auto = [r for r in find_fill(data, romset.IMAGES[image][3])
                + find_text(data, romset.IMAGES[image][3])
                if not any(overlaps(r, k) for k in kept)]
        write_map(path, image, kept + auto)
        counts = {k: sum(r["end"] - r["start"] + 1 for r in kept + auto if r["kind"] == k)
                  for k in sorted(KINDS)}
        print(f"{image:16} " + "  ".join(f"{k}={v:#x}" for k, v in counts.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
